import AppKit
import Observation
import UniformTypeIdentifiers

/// One thing that was copied.
struct ClipEntry: Identifiable, Codable, Hashable, Sendable {
    enum Kind: String, Codable, Sendable { case text, image, files }

    var id = UUID()
    var kind: Kind
    var text: String?
    /// PNG data, kept in memory only.
    var image: Data?
    var files: [URL]?
    var date = Date()
    var sourceApp: String?
    var isPinned = false

    var preview: String {
        switch kind {
        case .text: (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        case .image: "Image"
        case .files: files?.map(\.lastPathComponent).joined(separator: ", ") ?? "Files"
        }
    }

    var symbol: String {
        switch kind {
        case .text: (text ?? "").hasPrefix("http") ? "link" : "text.alignleft"
        case .image: "photo"
        case .files: "doc"
        }
    }

    enum CodingKeys: String, CodingKey { case id, kind, text, files, date, sourceApp, isPinned }
}

/// Clipboard history and the shelf.
@MainActor
@Observable
final class ClipboardHistory {
    private(set) var entries: [ClipEntry] = []
    /// Files parked on the shelf to drag out later.
    /// For the owl in the clipboard panel: a skipped password, a colour.
    var owlCue: OwlCue?
    @ObservationIgnored private(set) var lastSecretSkipped = Date.distantPast
    private(set) var shelf: [URL] = [] {
        didSet { if shelf != oldValue { onShelfChange?() } }
    }
    /// For the Nest under the notch, which shows or hides its tab to match.
    @ObservationIgnored var onShelfChange: (() -> Void)?

    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var task: Task<Void, Never>?
    @ObservationIgnored private var ignoreChange: Int?

    /// Password managers mark copies as concealed or transient (nspasteboard.org).
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    static let privateApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "com.apple.keychainaccess",
        "com.apple.Passwords", "com.lastpass.LastPass", "com.dashlane.Dashlane",
    ]

    private static var storeURL: URL? {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first?
            .appending(path: "Barn Owl/Clipboard.json")
    }

    private struct Store: Codable {
        var entries: [ClipEntry]
        var shelf: [URL]
    }

    init() {
        // Demo mode never reads or writes the real history.
        if DemoMode.isOn {
            entries = DemoMode.clipEntries()
            shelf = DemoMode.shelfFiles
            return
        }
        if let url = Self.storeURL, let data = try? Data(contentsOf: url),
           let store = try? JSONDecoder().decode(Store.self, from: data) {
            entries = Preferences.clipboardRemember ? store.entries : store.entries.filter(\.isPinned)
            shelf = store.shelf.filter { FileManager.default.fileExists(atPath: $0.path) }
        }
    }

    func start() {
        task = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: .milliseconds(500))
                self?.check()
            }
        }
        // Turning the history off, or "remember after quitting" off, takes
        // effect at once: in memory and on disk, not at the next copy.
        appliedSettings = (Preferences.clipboardEnabled, Preferences.clipboardRemember)
        settingsObserver = NotificationCenter.default.addObserver(
            forName: UserDefaults.didChangeNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.applySettings() }
        }
    }

    @ObservationIgnored private var settingsObserver: NSObjectProtocol?
    @ObservationIgnored private var appliedSettings: (enabled: Bool, remember: Bool)?

    func applySettings() {
        let now = (enabled: Preferences.clipboardEnabled, remember: Preferences.clipboardRemember)
        defer { appliedSettings = now }
        guard let before = appliedSettings, before != now else { return }
        if before.enabled, !now.enabled {
            clear()
        } else if before.remember, !now.remember {
            save(now: true)
        }
    }

    private func check() {
        guard !DemoMode.isOn else { return }
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        if ignoreChange == changeCount { return }
        guard Preferences.clipboardEnabled else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let app = NSWorkspace.shared.frontmostApplication
        guard types.isDisjoint(with: Self.privateTypes),
              !Self.privateApps.contains(app?.bundleIdentifier ?? "") else {
            // A password, most likely: the owl looks away.
            if types.contains("org.nspasteboard.ConcealedType") || Self.privateApps.contains(app?.bundleIdentifier ?? "") {
                lastSecretSkipped = Date()
                owlCue = OwlCue(.didntSee)
            }
            return
        }

        var entry: ClipEntry?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
            as? [URL], !urls.isEmpty {
            entry = ClipEntry(kind: .files, files: urls)
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            // A whole log file or database dump would sit in memory and be
            // rewritten to disk on every copy; history is for everyday snippets.
            guard text.utf8.count <= Self.largestText else {
                Log.app.info("Clipboard: skipped \(text.utf8.count) bytes of text, too large to keep")
                return
            }
            entry = ClipEntry(kind: .text, text: text)
        } else if let tiff = NSPasteboard.general.data(forType: .tiff) ?? NSImage(pasteboard: pasteboard)?.tiffRepresentation {
            // Turning a big screenshot into PNG takes a moment: not on the main thread.
            let source = app?.localizedName
            Task { [weak self] in
                guard let png = await Task.detached(operation: { Self.png(from: tiff) }).value else { return }
                var image = ClipEntry(kind: .image, image: png)
                image.sourceApp = source
                self?.add(image)
            }
            return
        }
        guard var entry else { return }
        entry.sourceApp = app?.localizedName
        add(entry)
        if let text = entry.text, let colour = colourFromHex(text) { owlCue = OwlCue(.colour(colour)) }
    }

    /// The most text one entry keeps: a megabyte.
    nonisolated static let largestText = 1_000_000

    /// PNG for the history, scaled down to at most 2,560 points on its long
    /// side, so a 6K screenshot doesn't take tens of megabytes of memory.
    nonisolated static func png(from tiff: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(tiff as CFData, nil) else { return nil }
        let options: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                        kCGImageSourceThumbnailMaxPixelSize: 2560,
                                        kCGImageSourceCreateThumbnailWithTransform: true]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }

    private func add(_ entry: ClipEntry) {
        // The same text again moves to the top instead of repeating.
        if let index = entries.firstIndex(where: { $0.kind == entry.kind && $0.text == entry.text
            && $0.files == entry.files && $0.image == entry.image }) {
            var existing = entries.remove(at: index)
            existing.date = Date()
            entries.insert(existing, at: 0)
        } else {
            entries.insert(entry, at: 0)
        }
        trim()
        save()
    }

    private func trim() {
        let limit = Preferences.clipboardLimit
        var unpinned = 0
        entries = entries.filter { entry in
            if entry.isPinned { return true }
            unpinned += 1
            return unpinned <= limit
        }
    }

    /// Puts the entry back on the clipboard.
    func copy(_ entry: ClipEntry) {
        if entry.kind == .image, entry.image == nil { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.kind {
        case .text: pasteboard.setString(entry.text ?? "", forType: .string)
        case .image: if let image = entry.image { pasteboard.setData(image, forType: .png) }
        case .files: pasteboard.writeObjects((entry.files ?? []) as [NSURL])
        }
        ignoreChange = pasteboard.changeCount
        changeCount = pasteboard.changeCount
        if let index = entries.firstIndex(where: { $0.id == entry.id }) {
            var moved = entries.remove(at: index)
            moved.date = Date()
            entries.insert(moved, at: 0)
            save()
        }
    }

    /// Copies the entry and pastes it into `app` with ⌘V.
    func paste(_ entry: ClipEntry, into app: NSRunningApplication?) {
        copy(entry)
        app?.activate()
        Task {
            try? await Task.sleep(for: .milliseconds(180))
            let source = CGEventSource(stateID: .hidSystemState)
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: down)  // V
                event?.flags = .maskCommand
                event?.post(tap: .cghidEventTap)
            }
        }
    }

    func togglePin(_ entry: ClipEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].isPinned.toggle()
        save()
    }

    func delete(_ entry: ClipEntry) {
        entries.removeAll { $0.id == entry.id }
        save()
    }

    /// Clears everything except pinned entries.
    func clear() {
        entries = entries.filter(\.isPinned)
        save(now: true)
    }

    // MARK: Shelf

    func addToShelf(_ urls: [URL]) {
        for url in urls where !shelf.contains(url) { shelf.append(url) }
        save()
    }

    func removeFromShelf(_ url: URL) {
        removeFromShelf([url])
    }

    func removeFromShelf(_ urls: [URL]) {
        shelf.removeAll { urls.contains($0) }
        save()
    }

    /// Lets go of files that were moved or deleted since they were dropped.
    func pruneShelf() {
        guard !DemoMode.isOn else { return }
        let existing = shelf.filter { FileManager.default.fileExists(atPath: $0.path) }
        if existing.count != shelf.count {
            shelf = existing
            save()
        }
    }

    func clearShelf() {
        shelf = []
        save(now: true)
    }

    @ObservationIgnored private var pendingSave: Task<Void, Never>?

    /// Writes the history to disk half a second after the last change, off
    /// the main thread, so a burst of copies costs one write.
    /// `now`: clearing must reach the disk at once, even if Barn Owl quits
    /// a moment later.
    private func save(now: Bool = false) {
        guard !DemoMode.isOn else { return }
        guard let url = Self.storeURL else { return }
        // Images are never written to disk, pinned or not.
        let kept = entries.filter { $0.kind != .image && (Preferences.clipboardRemember || $0.isPinned) }
        let store = Store(entries: kept, shelf: shelf)
        pendingSave?.cancel()
        if now {
            try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            if let data = try? JSONEncoder().encode(store) {
                try? data.write(to: url, options: [.atomic, .completeFileProtection])
            }
            return
        }
        pendingSave = Task {
            try? await Task.sleep(for: .milliseconds(500))
            guard !Task.isCancelled else { return }
            await Task.detached(priority: .utility) {
                try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
                if let data = try? JSONEncoder().encode(store) {
                    try? data.write(to: url, options: [.atomic, .completeFileProtection])
                }
            }.value
        }
    }
}
