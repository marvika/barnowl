#!/usr/bin/env python3
"""Bakes the pixel owlets from owlets.py into BarnOwl/Roost/OwletArt.swift.

Run from the repo root after changing owlets.py:  python3 Scripts/owlets/make-swift.py

Each frame becomes a string of W x H palette keys ("." is transparent), row by
row. The branch rows are left out: the app draws one continuous branch itself.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import owlets as P  # noqa: E402

OUT = os.path.join(HERE, "..", "..", "BarnOwl", "Roost", "OwletArt.swift")
BRANCH_ROWS = 2


def frame_string(f, w, h, drop_branch):
    rows = []
    for y in range(h):
        row = []
        for x in range(w):
            c = f.get((x, y), ".")
            if drop_branch and y >= h - BRANCH_ROWS:
                c = "."
            row.append(c)
        rows.append("".join(row))
    return "".join(rows)


def swift_frames(frames, w, h, drop_branch=True):
    return "[" + ", ".join(f'"{frame_string(f, w, h, drop_branch)}"' for f in frames) + "]"


def colour(hexstr):
    return "0x" + hexstr.lstrip("#").upper()


def main():
    keys = [k for k in P.PAL if k not in P._ALIAS]
    lines = [
        "// Generated by Scripts/owlets/make-swift.py from Scripts/owlets/owlets.py. Don't edit by hand.",
        "",
        "enum OwletArt {",
        f"    static let width = {P.W}",
        f"    static let height = {P.H}",
        "    static let iconSize = 16",
        "",
        "    /// Palette keys to 0xRRGGBB, per owl colour.",
        "    static let palettes: [String: [Character: UInt32]] = [",
    ]
    for name, pal in P.PALS.items():
        entries = ", ".join(f'"{k}": {colour(pal[k])}' for k in keys)
        lines.append(f'        "{name}": [{entries}],')
    lines += ["    ]", "", "    /// Each state's frames and how long one loop takes.",
              "    static let states: [String: (frames: [String], seconds: Double)] = ["]
    for key, _label, _caption, frames, dur in P.STATES:
        lines.append(f'        "{key}": ({swift_frames(frames, P.W, P.H)}, {dur}),')
    lines += ["    ]", "", "    /// 16 x 16 owlets for rows and badges.",
              "    static let icons: [String: (frames: [String], seconds: Double)] = ["]
    for key, (frames, dur) in P.ICONS.items():
        lines.append(f'        "{key}": ({swift_frames(frames, 16, 16, False)}, {dur or 1}),')
    lines += ["    ]", "", "    /// One-colour 16 x 16 owlets for the menu bar (\"o\" is ink).",
              "    static let templates: [String: String] = ["]
    for key, (frames, _dur) in P.ICONS.items():
        mono = P._mono(frames[0])
        lines.append(f'        "{key}": "{frame_string(mono, 16, 16, False)}",')
    lines += ["    ]", "}", ""]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT)} ({os.path.getsize(OUT) // 1024} KB)")


if __name__ == "__main__":
    main()
